/** Preserve verify-full, including hostname verification, without runtime file paths. */
export function verifiedSupabaseDatabaseConfig(
  connectionString: string,
): ClientConfig {
  const url = new URL(connectionString);
  const isSupabaseHost =
    url.hostname.endsWith(".pooler.supabase.com") ||
    /^db\.[a-z0-9]+\.supabase\.co$/.test(url.hostname);
  if (!isSupabaseHost || url.searchParams.get("sslmode") !== "verify-full") {
    return { connectionString };
  }
  // pg parses SSL URL parameters after ClientConfig; remove only the mode whose
  // semantics are supplied explicitly below so it cannot replace the pinned CA.
  if (
    ["sslcert", "sslkey", "sslrootcert", "ssl", "uselibpqcompat"].some((key) =>
      url.searchParams.has(key),
    )
  ) {
    throw new Error("COMUN_DATABASE_TLS_OPTIONS_CONFLICT");
  }
  url.searchParams.delete("sslmode");
  return {
    connectionString: url.toString(),
    ssl: { ca: SUPABASE_DATABASE_CA, rejectUnauthorized: true },
  };
}
