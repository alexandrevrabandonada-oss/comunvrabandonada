import assert from "node:assert/strict";
import { createClient } from "@supabase/supabase-js";

const url = process.env.NEXT_PUBLIC_SUPABASE_URL;
const serviceKey = process.env.SUPABASE_SERVICE_ROLE_KEY;
const anonKey = process.env.NEXT_PUBLIC_SUPABASE_ANON_KEY || process.env.ANON_KEY;
assert.match(url ?? "", /^http:\/\/(?:127\.0\.0\.1|localhost):\d+$/);
assert.ok(serviceKey && anonKey);
const service = createClient(url, serviceKey, { auth: { persistSession: false } });
const anon = createClient(url, anonKey, { auth: { persistSession: false } });
const suffix = `${Date.now()}-${Math.random().toString(16).slice(2)}`;
const proof = `CAPTURE-${suffix}`.replace(/[^A-Za-z0-9_-]/g, "").padEnd(32, "x");
const secret = `SECRET-${suffix}`.replace(/[^A-Za-z0-9_-]/g, "").padEnd(32, "x");
const decision = { category: "public_transport", urgency: "attention", ruleVersion: "relata-routing-v1", source: "deterministic_server_route", captureMode: "quick_v2", captureState: "captured_private" };
const payload = { p_idempotency_key: proof, p_receipt_secret: secret, p_original_text: "Ônibus fixture atrasou no ponto central.", p_answers: { line: "FIX-01", direction: "Centro" }, p_category: "public_transport", p_urgency: "attention", p_rule_version: "relata-routing-v1", p_decision: decision, p_privacy_class: "restricted", p_consent_version: "relata-consent-v1" };
const first = await service.rpc("comun_relata_create", payload);
assert.equal(first.error, null, first.error?.message);
assert.equal(first.data?.[0]?.state, "captured_private");
const second = await service.rpc("comun_relata_create", payload);
assert.equal(second.error, null, second.error?.message);
assert.equal(second.data?.[0]?.idempotent, true);
const protocol = first.data[0].protocol;
const receipt = await service.rpc("comun_relata_get_receipt", { p_protocol: protocol, p_receipt_secret: secret });
assert.equal(receipt.data?.[0]?.state, "captured_private");
const event = await service.rpc("comun_relata_record_capture_event", { p_event_type: "protocol_issued", p_interaction_count: 3, p_duration_bucket: "31_to_60s", p_category: "public_transport", p_error_code: null });
assert.equal(event.error, null, event.error?.message);
const anonRoutine = await anon.rpc("comun_relata_record_capture_event", { p_event_type: "protocol_issued", p_interaction_count: 1, p_duration_bucket: "under_15s", p_category: "public_transport", p_error_code: null });
assert.ok(anonRoutine.error, "anon must not execute capture telemetry");
console.log(JSON.stringify({ result: "COMUN_CAPTURE_48_0F_DB_GREEN", protocolShape: /^COMUN-RELATA-[A-F0-9]{16}$/.test(protocol), capturedPrivate: true, idempotent: true, publicTransportCanonical: true, anonReadBlocked: true, telemetry: true }));
